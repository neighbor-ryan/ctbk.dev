#!/usr/bin/env node
/** Regenerate the Docker allowlist from Git so newly added modules are included. */
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const tracked = execFileSync('git', ['ls-files', '-z', '--recurse-submodules'], { cwd: root, encoding: 'utf8' }).split('\0').filter(Boolean)
const extra = readFileSync(resolve(root, '.dockerinclude'), 'utf8').split('\n').filter(Boolean)
const paths = [...new Set([...tracked, ...extra])].sort()
const body = '# Generated by `pnpm docker:context` from Git and .dockerinclude\n*\n'
  + paths.map((path) => `!${path.replaceAll('[', '[[]')}`).join('\n') + '\n'
writeFileSync(resolve(root, '.dockerignore'), body)
console.log(`Docker context: ${paths.length} tracked/explicit paths`)
